import type { ComponentType, JSX } from 'preact'
import type { ToolId } from '../store'

const GRID = 22
const MINI = 11

function glyph(rows: string[], grid = GRID, cls = 'tool-ico'): JSX.Element {
    let minX = grid
    let minY = grid
    let maxX = -1
    let maxY = -1
    for (let y = 0; y < rows.length; y++) {
        const row = rows[y] ?? ''
        for (let x = 0; x < row.length; x++) {
            if (row[x] !== '#') continue
            if (x < minX) minX = x
            if (x > maxX) maxX = x
            if (y < minY) minY = y
            if (y > maxY) maxY = y
        }
    }
    const ox = maxX < 0 ? 0 : Math.round((grid - (maxX - minX + 1)) / 2) - minX
    const oy = maxY < 0 ? 0 : Math.round((grid - (maxY - minY + 1)) / 2) - minY

    const rects: JSX.Element[] = []
    for (let y = 0; y < rows.length; y++) {
        const row = rows[y] ?? ''
        let x = 0
        while (x < row.length) {
            if (row[x] === '#') {
                let w = 1
                while (row[x + w] === '#') w++
                rects.push(<rect key={`${x},${y}`} x={x + ox} y={y + oy} width={w} height={1} />)
                x += w
            } else {
                x++
            }
        }
    }
    return (
        <svg
            class={cls}
            viewBox={`0 0 ${grid} ${grid}`}
            fill="currentColor"
            shape-rendering="crispEdges"
            aria-hidden="true"
        >
            {rects}
        </svg>
    )
}

